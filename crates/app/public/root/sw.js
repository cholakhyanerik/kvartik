// На месте service worker, который стоял в корне сайта до переезда
// программы в /app/ (задача 65, 0.0.34). Его scope — «/», и он держит
// и корень, и /app/: открывает их прежней сборкой из своего кэша. Сам он
// не уйдёт: sw.js, которого больше нет (404), регистрацию с работающим
// worker не снимает (по спецификации Service Worker, «Update»: регистрация
// убирается, только если worker'а ещё не было; сверено 2026-10-16).
//
// Поэтому здесь — этот файл. Прежняя программа находит его, как любую
// новую версию, и говорит «Есть новая версия». Согласие человека
// («skip-waiting») включает его, а включившись, он снимает регистрацию:
// новые переходы она больше не перехватывает, а открытые вкладки доживают
// с ней («Unregister», там же). Прежняя программа перезагружает страницу,
// корень отвечает переадресацией на /app/ (_redirects), а `#/…` браузер
// переносит. Без согласия — как у любой версии (CLAUDE.md, Правило 2):
// перезагрузка сама посреди формы стёрла бы введённое.
//
// fetch он не слушает: запросы идут в сеть. Кэш прежней сборки удаляет
// service worker программы (app/sw.js), когда встаёт: кэши у них общие,
// по имени, и этот удалил бы и кэш программы. Убирать файл не нужно:
// прежний service worker может проснуться у человека, который месяц не
// заходил, а стоит файл здесь — ничего.
self.addEventListener("message", (event) => {
  if (event.data === "skip-waiting") {
    self.skipWaiting();
  }
});

self.addEventListener("activate", (event) => {
  event.waitUntil(self.registration.unregister());
});
