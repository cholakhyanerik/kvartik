//! Окно Kvartik в браузере: точка входа wasm.
//!
//! Крейт окна — тонкая оболочка: считать налог и деньги, решать бизнес-правила
//! и держать текст литералом здесь нельзя (таблица слоёв CLAUDE.md).

// Окно пока только открывает базу: записей в домене ещё нет, и чтение,
// запись и транзакции зовут одни браузерные тесты. Первая команда, которая
// пишет данные (задачи 53 и 9), снимет это ожидание — компилятор скажет сам,
// когда мёртвого кода не останется.
#[cfg_attr(
    not(all(test, target_arch = "wasm32")),
    expect(
        dead_code,
        reason = "API хранилища ждёт первую команду; пока его держат браузерные тесты"
    )
)]
mod store;
mod ui;

fn main() {
    // Первой строкой, до любого кода, который может упасть: иначе причина
    // паники пропадёт, и в консоли останется одно `unreachable` (Правило 6).
    console_error_panic_hook::set_once();
    leptos::mount::mount_to_body(ui::App);
}
