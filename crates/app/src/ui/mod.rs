//! Экраны и компоненты окна.
//!
//! Текст — только ключами `Key` из `kvartik_core::i18n`, цвета — только
//! переменными `tokens.css` (Правило 4; файл заводит задача 5).

use kvartik_core::i18n::{Key, Lang, t};
use leptos::prelude::*;

/// Корень окна. Пока — пустой экран каркаса: название сразу на трёх языках,
/// чтобы армянский и кириллица прошли весь путь от таблицы строк до
/// страницы с первой сборки. Выбора языка окна ещё нет.
#[component]
pub fn App() -> impl IntoView {
    view! {
        <main>
            {Lang::ALL
                .into_iter()
                // `lang` у каждого заголовка: по нему браузер выбирает шрифт
                // и правила переноса, а экранный диктор — произношение.
                .map(|lang| view! { <h1 lang=lang.code()>{t(lang, Key::AppName)}</h1> })
                .collect_view()}
        </main>
    }
}
