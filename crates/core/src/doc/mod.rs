//! Документы на бумаге (задача 12): счёт и акт — страницами и файлом PDF.
//!
//! Путь документа: [`sheet::Sheet::new`] собирает его строки на языке
//! документа; окно берёт у сайта файлы шрифтов, которые им нужны
//! ([`sheet::Sheet::needed_files`]), — те же, что у самого окна;
//! [`sheet::Sheet::pages`] раскладывает строки по страницам A4,
//! а [`pdf::write`] пишет страницы в файл. Превью в окне рисует те же
//! страницы ([`page`]), поэтому в нём ровно то, что в PDF (Правило 2).
//!
//! Ни браузера, ни хранилища здесь нет (таблица слоёв CLAUDE.md): шрифты
//! и логотип приходят байтами, а файл уходит байтами. Шрифты — в самих
//! файлах PDF, подмножеством: документ открывается одинаково на любом
//! устройстве и без сети.

pub mod font;
pub mod fonts;
