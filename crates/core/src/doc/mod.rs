use crate::model::document::{DocKind, Number};

/// Имя файла PDF: `Invoice-2026-001.pdf`, `Act-2026-001.pdf`. Латиницей на
/// любом языке документа: имя файла видят почта, мессенджер и банк клиента,
/// а латиница доходит без искажений везде.
pub fn file_name(kind: DocKind, number: Number) -> String {
    let kind = match kind {
        DocKind::Invoice => "Invoice",
        DocKind::Act => "Act",
    };
    format!("{kind}-{number}.pdf")
}

