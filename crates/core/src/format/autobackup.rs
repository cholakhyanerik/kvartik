//! Автокопия в папку человека (задача 29): имя файла, какие старые файлы
//! убрать и когда писать следующий. Папку и запись в неё знает окно
//! (`crates/app/src/platform/autobackup.rs`), а здесь — решения, которые
//! проверяются без браузера; время — параметром (Архитектура, «Время —
//! параметр»).
//!
//! Файл автокопии — тот же файл копии ([`super::backup`]): тот же замок,
//! пароль копий устройства и то же восстановление. Чтобы писать его без
//! человека, окно держит в браузере ключ из этого пароля — неизвлекаемым,
//! со своей солью, — а раз в [`CHECK_AFTER_DAYS`] дней просит пароль ввести
//! (решение человека 2026-11-03): пароль, который давно не вводили,
//! забывается, и файлы в облаке не открыл бы никто. Что ключ на устройстве
//! открывает и чего нет — шапка `crates/app/src/store/autobackup.rs`.
//!
//! # Имя
//!
//! `kvartik-auto-2026-11-03-1a2b.json`: день по календарю устройства и метка
//! устройства ([`DeviceTag`]). Файл — один на день: правок за день много,
//! и новая копия дня заменяет прежнюю, а в папке облака не копятся сотни
//! файлов. Метка — потому что в одну папку облака пишут два компьютера
//! человека: без неё они затирали бы копии друг друга, а каждый убирал бы
//! чужие. Сливает данные двух устройств восстановление копии (задача 41):
//! автокопию одного, восстановленную на другом, — как ручную. Ручная копия называется
//! иначе (`backup::file_name`), и её автокопия не трогает.
//!
//! Копия больше одного файла (задача 117) — файлы частей того же дня рядом:
//! `kvartik-auto-2026-11-03-1a2b-1of3.json`, `…-2of3.json` и `…-3of3.json`
//! (`backup::part_file_name`). Свои файлы дня — все его части.
//!
//! # Что убирается
//!
//! Только файлы этого устройства — имя целиком по образцу и с его меткой
//! ([`stale`]): автокопия пишет в свою папку «Kvartik» внутри выбранной, но
//! в неё может положить что угодно человек или облако. Остаются файлы [`KEEP`]
//! самых свежих дней, а у сегодняшнего — лишь только что записанные: копия
//! дня сменяет прежнюю копию дня, а у той частей могло быть больше.

use crate::model::date::Date;
use crate::model::record::Timestamp;

/// Начало имени файла автокопии: по нему окно перебирает в папке только
/// возможно свои файлы.
pub const PREFIX: &str = "kvartik-auto-";

/// Конец имени: тип файлу даёт расширение, как у ручной копии.
const SUFFIX: &str = ".json";

/// Своя папка автокопии внутри выбранной человеком. Хранится только она,
/// а не выбранная — та может быть корнем облака (ревью задачи 29;
/// `platform::autobackup::subfolder`). Имя — программы, латиницей на всех
/// языках, как знак на экране.
pub const FOLDER: &str = "Kvartik";

/// Выбрали саму свою папку — писать в неё, а не заводить в ней ещё одну:
/// так и включают автокопию снова в прежнюю папку.
pub fn own_folder(name: &str) -> bool {
    name.eq_ignore_ascii_case(FOLDER)
}

/// Как назвать папку автокопии человеку: пути браузер не даёт, есть только
/// имя выбранной папки — «OneDrive/Kvartik».
pub fn place(chosen: &str) -> String {
    if own_folder(chosen) {
        chosen.to_owned()
    } else {
        format!("{chosen}/{FOLDER}")
    }
}

/// Сколько дней своих файлов остаётся в папке — со всеми частями копии дня
/// (задача 117). Свежий нужен почти всегда сам:
/// восстановление сливает, а не заменяет (`backup::merge`), и файл старше не
/// отменит сделанного позже. Прежние нужны, только если свежий не читается —
/// облако прислало его не целиком, диск испортил. Семь — неделя, как
/// напоминание о копии (`backup::REMIND_AFTER_DAYS`): с файлами книги копия
/// бывает в десятки мегабайт, и держать больше в облаке человека дорого.
pub const KEEP: usize = 7;

/// Через столько после изменения пишется автокопия: одно дело человека —
/// часто несколько записей подряд (клиент, счёт, его выпуск), и копия через
/// минуту ловит их одним файлом.
pub const WAIT_MILLIS: i64 = 60_000;

/// И не чаще, чем раз в столько: каждая копия читает всю базу, сжимает
/// и шифрует её, а с файлами книги это секунды работы (Правило 1). Правки
/// за десять минут потеряет только браузер, стёрший данные именно в эти
/// десять минут.
pub const GAP_MILLIS: i64 = 10 * 60_000;

/// Через столько дней без ввода пароля копий окно просит его ввести (решение
/// человека 2026-11-03, шапка модуля).
pub const CHECK_AFTER_DAYS: i32 = 30;

/// Метка устройства в имени файла: четыре шестнадцатеричные цифры, случайные
/// на каждом устройстве. Совпасть у двух компьютеров одного человека она
/// может с вероятностью 1 к 65 536 — тогда они пишут в один файл дня, как
/// без метки.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct DeviceTag([u8; 4]);

impl DeviceTag {
    /// Новая метка. Случайность — та же, что у идентификаторов записей
    /// (`RecordId::random`): ядро берёт её само, на wasm32 — из WebCrypto.
    pub fn random() -> Self {
        let bytes = uuid::Uuid::new_v4().into_bytes();
        // Первые байты UUID v4 случайны целиком: версия и вариант — в шестом
        // и восьмом.
        let hex = |nibble: u8| b"0123456789abcdef"[usize::from(nibble)];
        Self([
            hex(bytes[0] >> 4),
            hex(bytes[0] & 0xf),
            hex(bytes[1] >> 4),
            hex(bytes[1] & 0xf),
        ])
    }

    /// Метка из записи; `None` — не четыре строчные шестнадцатеричные цифры.
    pub fn parse(text: &str) -> Option<Self> {
        let bytes: [u8; 4] = text.as_bytes().try_into().ok()?;
        bytes
            .iter()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(byte))
            .then_some(Self(bytes))
    }

    /// Запись метки — для хранилища устройства и имени файла.
    pub fn as_str(&self) -> &str {
        // Только цифры ASCII и буквы a–f: это проверено при создании.
        std::str::from_utf8(&self.0).unwrap_or_default()
    }
}

/// Имя файла автокопии этого дня на этом устройстве.
pub fn file_name(day: Date, tag: DeviceTag) -> String {
    format!("{PREFIX}{}-{}{SUFFIX}", day.iso(), tag.as_str())
}

/// День файла автокопии этого устройства — и одной копии, и её части
/// (шапка модуля); `None` — имя не его: чужое, другого устройства или
/// похожее, но не по образцу целиком.
pub fn day_of(name: &str, tag: DeviceTag) -> Option<Date> {
    let rest = name.strip_prefix(PREFIX)?.strip_suffix(SUFFIX)?;
    let (day, mark) = rest.split_at_checked(10)?;
    let mark = mark.strip_prefix('-')?;
    let part = match mark.split_at_checked(4) {
        Some((mark, "")) => mark == tag.as_str(),
        Some((mark, part)) => {
            mark == tag.as_str() && part.strip_prefix('-').and_then(super::backup::part_of_name).is_some()
        }
        None => false,
    };
    part.then_some(())?;
    Date::from_iso(day)
}

/// Файлы этого устройства, которые пора убрать: все свои не позже дня
/// `today`, кроме файлов [`KEEP`] самых свежих дней, — и сегодняшние, кроме
/// `written`: только что записанной копии дня. Чужие имена не попадают сюда
/// никогда (шапка модуля).
///
/// Свой файл с днём позже сегодняшнего не убирается и в [`KEEP`] не
/// считается: дню в имени верить нельзя. Его могли положить в общую папку
/// облака, а часы устройства могли уйти назад (Правило 6). Иначе семь таких
/// файлов стирали бы каждую новую автокопию сразу после записи — она
/// оказывалась бы самой старой, — и экран говорил бы, что копия есть
/// (найдено ревью задачи 29). Сегодняшний день тогда всегда самый свежий
/// из считаемых и остаётся.
///
/// Дни, а не файлы (задача 117): копия частями — несколько файлов одного
/// дня, и семь файлов оставили бы от прошлых дней обрывки. А сегодняшние,
/// кроме `written`, — прежняя копия дня, у которой частей было больше или
/// не было вовсе: новая копия дня сменяет её, как одним файлом.
pub fn stale<'a>(
    names: impl IntoIterator<Item = &'a str>,
    tag: DeviceTag,
    today: Date,
    written: &[&str],
) -> Vec<&'a str> {
    let own: Vec<(Date, &str)> = names
        .into_iter()
        .filter_map(|name| day_of(name, tag).map(|day| (day, name)))
        .filter(|(day, _)| *day <= today)
        .collect();
    let mut days: Vec<Date> = own.iter().map(|(day, _)| *day).collect();
    days.sort_unstable_by(|a, b| b.cmp(a));
    days.dedup();
    let kept = &days[..days.len().min(KEEP)];
    own.into_iter()
        .filter(|(day, name)| !kept.contains(day) || (*day == today && !written.contains(name)))
        .map(|(_, name)| name)
        .collect()
}

/// Брошенный временный файл своей автокопии прошлого дня: браузер пишет
/// копию во временный `<имя>.crswap` (или `<имя>.1.crswap`, если тот занят)
/// и подменяет им файл только в конце, а упавший посреди записи оставляет
/// его в папке навсегда (по исходникам Chromium, 2026-11-03), и облако
/// уносит его с собой. Сегодняшний не трогается: его, может быть, пишет
/// сейчас другая вкладка.
pub fn leftover(name: &str, tag: DeviceTag, today: Date) -> bool {
    let Some(rest) = name.strip_suffix(".crswap") else {
        return false;
    };
    // `.1`, `.2`… перед `.crswap` — номер временного файла.
    let file = match rest.rsplit_once('.') {
        Some((file, number)) if !number.is_empty() && number.bytes().all(|byte| byte.is_ascii_digit()) => file,
        _ => rest,
    };
    day_of(file, tag).is_some_and(|day| day < today)
}

/// Есть ли изменения, которых нет в последней автокопии: `changed` — момент
/// последней записи в базу, `done` — момент, когда последняя удавшаяся
/// автокопия начала читать базу. Запись в тот же миг — не в копии: лучше
/// лишняя копия, чем пропущенная правка.
pub fn pending(changed: Option<Timestamp>, done: Option<Timestamp>) -> bool {
    changed.is_some_and(|changed| done.is_none_or(|done| changed >= done))
}

/// Через столько после того, как автокопия заработала в окне, она
/// освежается, если изменений нет ([`refresh_due`]): рабочий экран к этому
/// времени давно готов, а заход ради одной оплаты длится секунды.
pub const REFRESH_WAIT_MILLIS: i64 = 10_000;

/// Пора ли записать автокопию, хотя изменений нет: сегодня её ещё не было,
/// не было вовсе — или её момент «из будущего», и ему верить нельзя (часы
/// переводили, Правило 6). Так день последней копии не стареет, пока
/// автокопия может писать, а удалённая папка или снятое разрешение выдают
/// себя в тот же день, а не ждут правки; напоминание о копии считается
/// только по дню сделанной копии (`backup::reminder_due`, решение человека
/// 2026-11-03). Без этого автокопия, которой ни разу не удалось записать
/// данные, введённые до неё, молчала бы до первой правки (ревью задачи 29).
/// `done_day` — день `done` по календарю устройства.
pub fn refresh_due(done: Option<Timestamp>, now: Timestamp, done_day: Option<Date>, today: Date) -> bool {
    done.is_none_or(|done| done > now || done_day != Some(today))
}

/// Через сколько миллисекунд писать автокопию, если она нужна сейчас:
/// не раньше [`WAIT_MILLIS`] и не раньше [`GAP_MILLIS`] после последней.
/// Последняя «из будущего» — это часы, которые переводили (Правило 6), и она
/// не откладывает копию: иначе автокопий не было бы, пока часы не догонят.
pub fn delay(done: Option<Timestamp>, now: Timestamp) -> i64 {
    let since = done
        .filter(|done| *done <= now)
        .map(|done| now.unix_millis() - done.unix_millis());
    since.map_or(WAIT_MILLIS, |since| WAIT_MILLIS.max(GAP_MILLIS - since))
}

/// Пора ли попросить пароль копий: его не вводили [`CHECK_AFTER_DAYS`] дней
/// или неизвестно, когда вводили. День «из будущего» — часы, а не ввод, и не
/// повод просить.
pub fn check_due(entered: Option<Date>, today: Date) -> bool {
    entered.is_none_or(|entered| today.days_since(entered) >= CHECK_AFTER_DAYS)
}

