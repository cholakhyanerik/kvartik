//! Налоги: правила как данные — с датами действия и источником.
//!
//! Правило налога — данные с источником (Правило 2): закон, статья,
//! ссылка и дата сверки, а у правил, которые менялись или изменятся, —
//! ещё и даты действия. Правило без источника — догадка, и сюда оно не
//! идёт (Правило 6). Ставку или срок константой в коде не держат:
//! правило берётся на нужную дату, а не «текущее».
//!
//! Пока здесь только то, что нужно профилю ИП (задача 9): кто не может
//! быть на налоге с оборота ([`turnover`]) и кто вступает в накопительную
//! пенсию добровольно ([`annual`]). Файл правил с версиями (`2026.1`…) —
//! задача 18: эти записи переедут в него. Расчёты — задачи 19 и 20.

pub mod annual;
pub mod turnover;

use crate::model::date::Date;

/// Откуда правило: закон, статья, ссылка на текст и когда его сверили.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Source {
    /// Закон: номер и название, как на arlis.am.
    pub law: &'static str,
    /// Статья, часть, пункт.
    pub article: &'static str,
    /// Ссылка на текст закона.
    pub url: &'static str,
    /// Когда текст сверен.
    pub checked: Date,
}

/// Дата для записи правила: в правилах — только существующие даты, и тест
/// модуля это держит.
const fn date(year: u16, month: u8, day: u8) -> Date {
    match Date::new(year, month, day) {
        Some(date) => date,
        None => panic!("в правилах — только существующие даты"),
    }
}
