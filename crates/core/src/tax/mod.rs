//! Налоги: правила как данные — с датами действия и источником.
//!
//! Правило налога — данные с источником (Правило 2): закон, статья,
//! ссылка и дата сверки, а ещё дни, с которого и по который оно действует.
//! Правило без источника — догадка, и сюда оно не идёт (Правило 6). Ставку
//! или срок константой в коде не держат: правило берётся из файла правил
//! ([`rules`]) на нужную дату, а не «текущее».
