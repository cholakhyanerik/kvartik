//! Налог с оборота (задача 19).
//!
//! Пока здесь одно правило — кто не может быть плательщиком налога
//! с оборота по виду деятельности. Окно говорит о нём сразу, когда человек
//! вписывает код в профиль (задача 9), а не в конце квартала. Расчёт налога
//! квартала — задача 19, после сверки с бухгалтером (задача 17).

use super::{Source, date};
use crate::model::activity::ActivityCode;
use crate::model::date::Date;

/// Правило «кто ведёт такую деятельность, не плательщик налога с оборота».
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct Exclusion {
    /// Коды, как их пишет закон: раздел (`69`) или группа (`78.2`).
    pub codes: &'static [&'static str],
    /// С какого дня действует.
    pub from: Date,
    /// По какой день действует; `None` — действует.
    pub until: Option<Date>,
    pub source: Source,
}

/// Налоговый кодекс, ст. 254, ч. 3, п. 3.1: плательщиками налога с оборота
/// не могут быть «69. Իրավաբանական և հաշվապահական գործունեություն»,
/// «70. Գլխամասային գրասենյակների գործունեություն. կառավարման հարցերով
/// խորհրդատվական ծառայություններ», «78.2. Ժամանակավոր աշխատուժով
/// ապահովման գործունեություն», «78.3. Աշխատուժով ապահովման այլ
/// գործունեություն» «…գործունեություններ իրականացնողները» — те, кто ведёт
/// эту деятельность.
///
/// Это про человека целиком, а не про оборот одного вида: ИП —
/// плательщик налога с оборота «по всем видам деятельности» (ст. 254,
/// ч. 4), а с дня, когда такая деятельность началась, перестаёт им быть до
/// конца года (ст. 255, ч. 1, п. 3). Пункт 3.1 внёс закон ՀՕ-72-Ն, ст. 2;
/// в силе с 2025-07-01 (там же, ст. 9, ч. 3), без переходных правил.
/// Сверено по тексту на arlis.am 2026-10-12 (по закону; разведка
/// задачи 9). Ведёт ли деятельность тот, у кого код записан в реестре,
/// но не используется, закон не говорит — поэтому окно говорит «кто ведёт»
/// и советует сверить с бухгалтером.
pub const EXCLUSIONS: &[Exclusion] = &[Exclusion {
    codes: &["69", "70", "78.2", "78.3"],
    from: date(2025, 7, 1),
    until: None,
    source: Source {
        law: "ՀՕ-165-Ն ՀՀ հարկային օրենսգիրք (ՀՕ-72-Ն)",
        article: "հոդված 254, մաս 3, կետ 3.1; մաս 4",
        url: "https://www.arlis.am/hy/acts/230455",
        checked: date(2026, 10, 12),
    },
}];

/// Закрывает ли код налог с оборота в день `on`: правило, по которому
/// закрывает, или `None`.
pub fn excluded(code: &ActivityCode, on: Date) -> Option<&'static Exclusion> {
    EXCLUSIONS.iter().find(|rule| {
        rule.from <= on
            && rule.until.is_none_or(|until| on <= until)
            && rule.codes.iter().any(|prefix| code.starts_with(prefix))
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn code(text: &str) -> ActivityCode {
        ActivityCode::parse(text).expect("в тесте — годный код")
    }

    fn day(year: u16, month: u8, day: u8) -> Date {
        Date::new(year, month, day).expect("в тесте — существующая дата")
    }

    /// Закрывают налог с оборота коды разделов 69 и 70 и групп 78.2 и 78.3,
    /// а соседние — нет; ожидаемое выписано человеком по тексту ст. 254.
    #[test]
    fn excluded_codes_follow_article_254() {
        let today = day(2026, 10, 12);
        let closed = ["69.10.0", "69.20.0", "70.10.0", "70.21.0", "70.22.0", "78.20.0", "78.30.0"];
        let open = ["62.01.0", "71.11.0", "73.11.0", "74.30.0", "78.10.0", "68.20.0", "63.11.1"];
        let mut wrong = Vec::new();
        for text in closed {
            if excluded(&code(text), today).is_none() {
                wrong.push(format!("{text} не закрывает"));
            }
        }
        for text in open {
            if excluded(&code(text), today).is_some() {
                wrong.push(format!("{text} закрывает"));
            }
        }
        assert!(wrong.is_empty(), "правило ст. 254: {wrong:#?}");
    }

    /// До 1 июля 2025 года правила не было (ՀՕ-72-Ն, ст. 9, ч. 3).
    #[test]
    fn excluded_only_since_july_2025() {
        let consulting = code("70.22.0");
        assert!(excluded(&consulting, day(2025, 6, 30)).is_none());
        assert!(excluded(&consulting, day(2025, 7, 1)).is_some());
    }
}
