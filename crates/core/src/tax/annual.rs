//! Годовые платежи ИП: налог на прибыль, соцплатёж, гербовый сбор,
//! медстраховка (задача 20).
//!
//! Пока здесь одно правило — кто участвует в накопительной пенсии (платит
//! соцплатёж) без выбора, а кто — только если вступил сам: от него зависит,
//! о чём спросить человека в профиле (задача 9). Расчёт сумм и сроков —
//! задача 20 — по ответам бухгалтера 2026-10-19 (FEATURE_TASKS.md, «PDF
//! против текста закона», строки о годовых платежах).

use super::{Source, date};
use crate::model::date::Date;

/// Кто участвует в накопительной пенсии по закону, а кто — по своему
/// выбору.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub struct FundedPension {
    /// Родившиеся в этот день и позже — участники обязательно; раньше —
    /// только если подали заявление о выборе пенсионного фонда.
    pub mandatory_born_from: Date,
    pub source: Source,
}

/// Закон о накопительных пенсиях, ст. 5, ч. 1: участники — «1974 թվականի
/// հունվարի 1-ին և դրանից հետո ծնված … անհատ ձեռնարկատերերը» (п. 1),
/// а родившиеся «մինչև 1974 թվականը» — если подали заявление о выборе
/// фонда (п. 2); решение не пересматривается (ч. 2). Иностранец
/// и лицо без гражданства с правом проживания (статусом проживания)
/// платят на общих основаниях (ч. 3). Сверено по сводному тексту на arlis.am
/// (по закону; сводный текст arlis помечает неофициальным) — 2026-10-12.
/// Даты действия правила не сверялись: оно решает только, о чём спросить
/// в профиле, а сумму считает задача 20.
pub const FUNDED_PENSION: FundedPension = FundedPension {
    mandatory_born_from: date(1974, 1, 1),
    source: Source {
        law: "ՀՕ-244-Ն «Կուտակային կենսաթոշակների մասին»",
        article: "հոդված 5, մաս 1, կետեր 1–2, մասեր 2–3",
        url: "https://www.arlis.am/hy/acts/224823/latest",
        checked: date(2026, 10, 12),
    },
};

/// Решает ли человек сам, участвовать ли в накопительной пенсии: родился
/// раньше границы. Граница — 1 января, поэтому хватает года рождения.
pub const fn pension_is_a_choice(birth_year: u16) -> bool {
    birth_year < FUNDED_PENSION.mandatory_born_from.year()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Граница — 1 января 1974 года: родившийся в 1974-м — участник
    /// обязательно, в 1973-м — по выбору. Граница — первый день года, иначе
    /// одного года рождения не хватило бы.
    #[test]
    fn born_in_1974_is_mandatory() {
        assert_eq!(FUNDED_PENSION.mandatory_born_from.month(), 1);
        assert_eq!(FUNDED_PENSION.mandatory_born_from.day(), 1);
        assert!(pension_is_a_choice(1973));
        assert!(!pension_is_a_choice(1974));
        assert!(!pension_is_a_choice(1990));
    }
}
