//! Годовые платежи ИП: налог на прибыль, соцплатёж, гербовый сбор,
//! медстраховка (задача 20).
//!
//! Пока здесь одно правило — кто участвует в накопительной пенсии (платит
//! соцплатёж) без выбора, а кто — только если вступил сам: от него зависит,
//! о чём спросить человека в профиле (задача 9). Расчёт сумм и сроков —
//! задача 20 — по ответам бухгалтера 2026-10-19 (FEATURE_TASKS.md, «PDF
//! против текста закона», строки о годовых платежах).

use super::rules::{self, FundedPension, Rule};
use crate::model::date::Date;

/// Правило накопительной пенсии на день `on`; `None` — правила на этот
/// день нет.
///
/// Правила — `funded_pension` файла правил. Сейчас это закон
/// о накопительных пенсиях, ст. 5, ч. 1: соцплатёж делают «1974 թվականի
/// հունվարի 1-ին և դրանից հետո ծնված … անհատ ձեռնարկատերերը» (п. 1), а
/// родившиеся «մինչև 1974 թվականը» — если подали заявление о выборе фонда
/// (п. 2); решение не пересматривается (ч. 2). Иностранец и лицо без
/// гражданства с правом проживания (статусом проживания) платят на общих
/// основаниях, если международный договор не говорит иное (ч. 3).
///
/// Текст ч. 1–3 — с 2014-07-01 (ՀՕ-67-Ն от 21.06.2014; поправки после него
/// правили только ч. 5–11), но до 2018-07-01 тот, кто уже был ИП, мог
/// отказаться от платежа заявлением (ст. 81, ч. 1 и 3; срок — ՀՕ-76-Ն от
/// 12.05.2016). Поэтому правило без исключений и в файле — с 2018-07-01
/// (по закону; сверено по тексту arlis 224823, 91047, 106108 и поправок
/// 2017–2024 годов 2026-10-19, разведка задачи 18).
pub fn funded_pension(on: Date) -> Option<&'static FundedPension> {
    rules::armenia()
        .funded_pension()
        .iter()
        .find(|rule| rule.period().contains(on))
}

/// Решает ли человек сам, участвовать ли в накопительной пенсии, — по
/// правилу на день `on`: родился раньше границы. Граница — 1 января (это
/// держит разбор файла правил), поэтому хватает года рождения. `false` —
/// участие обязательно или правила на этот день нет: спрашивать не о чем.
pub fn pension_is_a_choice(birth_year: u16, on: Date) -> bool {
    funded_pension(on).is_some_and(|rule| birth_year < rule.mandatory_born_from.year())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn day(year: u16, month: u8, day: u8) -> Date {
        Date::new(year, month, day).expect("в тесте — существующая дата")
    }

    /// Граница — 1 января 1974 года: родившийся в 1974-м — участник
    /// обязательно, в 1973-м — по выбору. Граница — первый день года, иначе
    /// одного года рождения не хватило бы.
    #[test]
    fn born_in_1974_is_mandatory() {
        let today = day(2026, 10, 19);
        let rule = funded_pension(today).expect("правило на сегодня есть");
        assert_eq!(rule.mandatory_born_from, day(1974, 1, 1));
        assert!(pension_is_a_choice(1973, today));
        assert!(!pension_is_a_choice(1974, today));
        assert!(!pension_is_a_choice(1990, today));
    }

    /// Без исключений правило действует с 1 июля 2018 года: до того тот, кто
    /// уже был ИП, мог отказаться от платежа (ст. 81, ч. 1 и 3). Правила на
    /// день нет — и спрашивать не о чем.
    #[test]
    fn pension_rule_since_july_2018() {
        assert!(funded_pension(day(2018, 6, 30)).is_none());
        assert!(funded_pension(day(2018, 7, 1)).is_some());
        assert!(!pension_is_a_choice(1960, day(2018, 6, 30)));
        assert!(pension_is_a_choice(1960, day(2018, 7, 1)));
    }
}
