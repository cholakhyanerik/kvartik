/// Язык окна или документа.
///
/// Вариант армянского называется `Am`, как в Arpa и Savio, но код в файлах
/// и настройках — `hy` (ISO 639-1): `am` — это амхарский.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Hash)]
pub enum Lang {
    Am,
    Ru,
    En,
}

impl Lang {
    /// Все языки. Порядок — армянский первым: программа для ИП Армении.
    pub const ALL: [Lang; 3] = [Lang::Am, Lang::Ru, Lang::En];

    /// Код для настроек, файлов и атрибута `lang` в разметке. Двухбуквенный
    /// и устойчивый: имя варианта менять можно, а это — нет, иначе у всех
    /// разом слетит запомненный выбор языка.
    pub const fn code(self) -> &'static str {
        match self {
            Lang::Am => "hy",
            Lang::Ru => "ru",
            Lang::En => "en",
        }
    }

    /// Разбирает код из настроек или файла. `None` — код чужой.
    pub fn from_code(code: &str) -> Option<Self> {
        Self::ALL.into_iter().find(|lang| lang.code() == code)
    }

    /// Имя языка на нём самом — для переключателя языка окна. Не перевод:
    /// человек, открывший окно на чужом языке, ищет свой глазами (опыт
    /// Arpa).
    pub const fn native_name(self) -> &'static str {
        match self {
            Lang::Am => "Հայերեն",
            Lang::Ru => "Русский",
            Lang::En => "English",
        }
    }

    /// Язык окна, пока человек не выбрал свой: первый из языков браузера
    /// (`navigator.languages`, по убыванию предпочтения), который знает
    /// программа, а не нашлось ни одного — армянский (решение человека
    /// 2026-10-12, задача 53; так же берёт имя программы манифест).
    ///
    /// Сравнивается основной подтег без учёта регистра: `ru-RU` — русский,
    /// `hy-AM` — армянский. `am` — амхарский, а не армянский.
    pub fn preferred<'a>(tags: impl IntoIterator<Item = &'a str>) -> Self {
        tags.into_iter()
            .find_map(|tag| {
                let primary = tag.split(['-', '_']).next().unwrap_or(tag);
                Self::ALL
                    .into_iter()
                    .find(|lang| lang.code().eq_ignore_ascii_case(primary))
            })
            .unwrap_or(Lang::Am)
    }
}

/// В данных язык — его код (`"hy"`, `"ru"`, `"en"`): язык документов
/// у клиента (задача 10) и у документа (задача 11). Имя варианта в данные не
/// идёт, как и в настройки окна.
impl Serialize for Lang {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_str(self.code())
    }
}

/// Читается только код из `Lang::code`: `"am"` (амхарский) или `"HY"` — порча.
impl<'de> Deserialize<'de> for Lang {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let text = String::deserialize(deserializer)?;
        Self::from_code(&text).ok_or_else(|| {
            de::Error::invalid_value(de::Unexpected::Str(&text), &"код языка: hy, ru или en")
        })
    }
}

/// Ключ строки, которую видит человек, — её три перевода: русский,
/// английский, армянский.
///
/// Постоянная, а не сама строка: по имени ключа компилятор ловит опечатку,
/// а по русскому тексту — нет. И постоянная, а не вариант перечисления
/// (задача 80): перечисление читал один `match` на всю таблицу, и все
/// строки окна лежали в главном wasm — и те, что рисуют только части
/// (`crates/app/src/ui/split.rs`), 46 КБ после brotli на 0.0.56. Постоянную
/// каждое место вызова берёт себе вместе с её строками, и программа разреза
/// кладёт их туда, где их зовёт код, — сама, без списков строк по частям:
/// в главный модуль, в часть или, когда ключ нужен нескольким частям,
/// в их общий кусок, как общий код (CLAUDE.md, Правила 1 и 6). Что
/// механизм жив, проверяет хук сборки (`crates/sw/src/wasm.rs`).
///
/// Ключи равны, когда равны их строки: адреса у постоянной Rust не обещает.
/// Собрать ключ можно только здесь, макросом `strings!`.
#[derive(Clone, Copy, PartialEq, Eq, Hash)]
pub struct Key(&'static Texts);

/// Три перевода ключа одной строкой подряд — русский, английский,
/// армянский — и длины первых двух в байтах.
///
/// Одной строкой, а не тремя: одинаковые строки компоновщик сливает в одну,
/// а слитая лежит там, где её зовёт хоть кто-то. Английское «Amount» двух
/// ключей слилось с тем же словом из `derive(Debug)` ядра и легло отдельным
/// файлом, который грузили и части копии (замер задачи 80). Строка подряд
/// у каждого ключа своя, и зовёт её только он.
#[derive(PartialEq, Eq, Hash)]
struct Texts {
    all: &'static str,
    ru: u16,
    en: u16,
}

impl Texts {
    /// `all` — три перевода подряд, `ru` и `en` — длины первых двух.
    /// Строка длиннее 64 КБ не соберётся: сборка остановится здесь.
    const fn new(all: &'static str, ru: usize, en: usize) -> Self {
        assert!(ru + en <= u16::MAX as usize, "перевод длиннее 64 КБ");
        Self {
            all,
            ru: ru as u16,
            en: en as u16,
        }
    }
}

/// Строка на выбранном языке. Ничего не собирает и не выделяет.
pub const fn t(lang: Lang, key: Key) -> &'static str {
    let Texts { all, ru, en } = key.0;
    let (ru, en) = (*ru as usize, *en as usize);
    let (first, am) = all.split_at(ru + en);
    let (ru, en) = first.split_at(ru);
    match lang {
        Lang::Ru => ru,
        Lang::En => en,
        Lang::Am => am,
    }
}

/// Ключ в отчёте теста — его строка по-русски: имени ключа в нём нет.
impl std::fmt::Debug for Key {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_tuple("Key").field(&t(Lang::Ru, *self)).finish()
    }
}

/// Объявляет ключи: у каждого — описание здесь и строка того же имени
/// в каждом файле языка (макросы `ru!`, `en!`, `hy!`).
///
/// Языки — тремя файлами (задача 119), а ключ — одним списком, ровно затем,
/// чтобы переводы **нельзя** было разъехать: ключ без строки одного языка не
/// соберётся (опыт Savio), а строку без ключа ловит тест
/// `every_string_has_a_key`. Переводы склеивает `concat!` — он раскрывает
/// макросы языков в литералы, и строка выходит той же, что до разделения.
/// Склейка постоянными `const fn` давала те же байты, но в другом порядке, и
/// главный wasm после brotli вырос на 634 Б (замер задачи 119).
macro_rules! strings {
    ($( $(#[$meta:meta])* $key:ident; )*) => {
        // Имена — как у вариантов перечисления, которым ключи были до
        // задачи 80: места вызова пишут `Key::…`, как прежде.
        #[allow(non_upper_case_globals)]
        impl Key {
            $(
                $(#[$meta])*
                pub const $key: Key =
                    Key(&Texts::new(concat!(ru!($key), en!($key), hy!($key)), ru!($key).len(), en!($key).len()));
            )*
        }

        /// Все ключи вместе с их именами — для проверок таблицы: полноты здесь
        /// и знаков в шрифтах окна (`crates/app/tests/fonts.rs`). Открыт, а не
        /// `#[cfg(test)]`: тест другого крейта видит ядро как обычную
        /// зависимость. В wasm окна массива нет, пока его никто не зовёт,
        /// а позови его код окна — все строки легли бы туда, где этот код.
        pub const ALL_KEYS: &[(Key, &str)] = &[ $( (Key::$key, stringify!($key)), )* ];
    };
}

