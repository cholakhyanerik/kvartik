/// Подставляет значения в шаблон вместо `{}`, по порядку.
///
/// Своя подстановка, а не `format!`: `format!` требует строку-литерал, а
/// шаблон приезжает из таблицы. Порядок мест — порядок `{}` в самом шаблоне,
/// и ради этого она и нужна: в армянском число и слово стоят иначе, чем
/// в русском, и склейка кусками на стороне вызова зашила бы русский порядок
/// слов во все три языка (опыт Savio).
///
/// Лишний `{}` остаётся в строке как есть: видимая дыра лучше молча
/// съеденного куска текста.
pub fn fill(template: &str, args: &[&str]) -> String {
    let mut out =
        String::with_capacity(template.len() + args.iter().map(|arg| arg.len()).sum::<usize>());
    let mut rest = template;
    let mut args = args.iter();
    while let Some(at) = rest.find("{}") {
        let Some(arg) = args.next() else {
            break;
        };
        out.push_str(&rest[..at]);
        out.push_str(arg);
        rest = &rest[at + 2..];
    }
    out.push_str(rest);
    out
}

/// Ошибка введённого числа — словами, с примером верной записи `example` на
/// языке `lang`. Одна на окно и калькулятор лендинга (задача 34): поле суммы
/// у них разбирает один [`parse_money`], и слова о его ошибке не должны
/// расходиться.
pub fn number_problem(lang: Lang, error: ParseError, example: &str) -> String {
    match error {
        ParseError::Empty => fill(t(lang, Key::NumberEmpty), &[example]),
        ParseError::Invalid => fill(t(lang, Key::NumberInvalid), &[example]),
        ParseError::Separators => fill(t(lang, Key::NumberSeparators), &[example]),
        ParseError::TooPrecise { max: 0 } => fill(t(lang, Key::NumberWhole), &[example]),
        ParseError::TooPrecise { max } => {
            fill(t(lang, Key::NumberTooPrecise), &[&integer(lang, i64::from(max)), example])
        }
        ParseError::TooLarge => t(lang, Key::NumberTooLarge).to_owned(),
    }
}

/// Форма слова при числительном.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
enum Plural {
    One,
    Few,
    Many,
}

/// Какая форма слова нужна при числе `n`.
///
/// Русскому нужны три: «1 счёт, 2 счёта, 5 счетов», и одиннадцать —
/// четырнадцать — исключение: «11 счетов», «112 счетов». Правило совпадает
/// с CLDR 48 на всех числах от 0 до 2000 (сверено с `Intl.PluralRules`
/// 2026-10-11). Английскому нужны две, `Few` у него не бывает.
///
/// Армянскому — одна: при числительном существительное остаётся
/// в единственном числе, «5 հաշիվ» (решение человека 2026-10-11, как
/// в Arpa и Savio). У CLDR для армянского две категории — `one` для 0 и 1
/// и `other`, — но форму существительного при числе они не меняют.
const fn plural_form(lang: Lang, n: u64) -> Plural {
    match lang {
        Lang::Ru => {
            if n % 100 >= 11 && n % 100 <= 14 {
                Plural::Many
            } else {
                match n % 10 {
                    1 => Plural::One,
                    2..=4 => Plural::Few,
                    _ => Plural::Many,
                }
            }
        }
        Lang::En => {
            if n == 1 {
                Plural::One
            } else {
                Plural::Many
            }
        }
        Lang::Am => Plural::One,
    }
}

/// Форма слова при числе `n` из ключей `…One`, `…Few`, `…Many`.
///
/// Ключей всегда три, потому что их требует русский. В английском переводе
/// `…Few` повторяет `…Many`, а в армянском все три одинаковы — это правило
/// языка, а не упрощение. Само число записывает [`integer`]: «1 000 счетов»,
/// а не «1000 счетов».
pub const fn plural(lang: Lang, n: u64, one: Key, few: Key, many: Key) -> &'static str {
    let key = match plural_form(lang, n) {
        Plural::One => one,
        Plural::Few => few,
        Plural::Many => many,
    };
    t(lang, key)
}

/// Что не так с записью текста на языке `lang`; `None` — всё так. Правила
/// одни у таблицы строк (тест ниже) и у заметок «Что нового»
/// (`crates/app/tests/notes.rs`, задача 67): их читает тот же человек, а
/// пишут их так же — копированием русской строки. Открыта, как
/// [`ALL_KEYS`], ради теста другого крейта; в wasm окна её нет, пока её
/// никто не зовёт.
///
/// - Ни пробелов подряд, ни пробела по краям — признака потерянного
///   переноса строки в исходнике (опыт Savio).
/// - Тире не начинает строку: перед ним неразрывный пробел (U+00A0).
///   С обычным перенос оставляет «— при его закрытии» в начале строки — на
///   телефоне это видно сразу (глазной прогон задачи 6).
/// - Кавычки принадлежат языку, а не строке (Правило 4): «ёлочки» —
///   в русском и армянском, “лапки” — в английском. Кавычки внутри кавычек
///   в русском — „немецкие“: открывает их U+201E, а закрывает U+201C — та
///   же, что открывает английские. Поэтому пара „…“ своя, а “ без „ перед
///   ней — английская.
/// - Ни буквы кириллицы в английском и армянском: так выглядит скопированная
///   и переведённая не целиком русская строка (опыт Arpa).
/// - Армянский определённый артикль перед словом на гласный звук — «ն»,
///   а не «ը»: «տեսակն ակտում», а не «տեսակը ակտում» (задача 81). Гласный
///   звук в начале слова — «ա», «է», «ը», «ի», «օ» и «ու»; «ե», «ո» и «և»
///   там звучат [йе], [во] и [йев], и перед ними «ը» остаётся: «ծրագիրը
///   երկար», «օրը ոչ», «էջը և» (решение человека 2026-10-23). После
///   запятой и другой паузы «ը» остаётся тоже: правило — для слов подряд
///   через пробел.
pub fn flaw(lang: Lang, text: &str) -> Option<&'static str> {
    if text.contains("  ") || text.starts_with(' ') || text.ends_with(' ') {
        return Some("пробелы подряд или по краям");
    }
    if text.contains(" —") || text.starts_with('—') {
        return Some("тире после обычного пробела");
    }
    let foreign_quotes = match lang {
        Lang::En => text.contains(['«', '»', '„']),
        Lang::Ru | Lang::Am => {
            let mut nested = false;
            let english = text.chars().any(|c| match c {
                '„' if !nested => {
                    nested = true;
                    false
                }
                '“' if nested => {
                    nested = false;
                    false
                }
                '„' | '“' | '”' => true,
                _ => false,
            });
            english || nested
        }
    };
    if foreign_quotes {
        return Some("кавычки не того языка");
    }
    let cyrillic = |c: char| ('\u{400}'..='\u{4FF}').contains(&c);
    if matches!(lang, Lang::En | Lang::Am) && text.chars().any(cyrillic) {
        return Some("кириллица в переводе");
    }
    let vowel_first = |word: &str| {
        word.starts_with(['ա', 'է', 'ը', 'ի', 'օ', 'Ա', 'Է', 'Ը', 'Ի', 'Օ'])
            || word.starts_with("ու")
            || word.starts_with("Ու")
            || word.starts_with("ՈՒ")
    };
    let words = || text.split(' ');
    if lang == Lang::Am
        && words()
            .zip(words().skip(1))
            .any(|(word, next)| word.ends_with('ը') && vowel_first(next))
    {
        return Some("«ը» перед гласной: нужно «ն»");
    }
    None
}

