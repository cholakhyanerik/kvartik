// Образцы файла копии выпущенных версий (Правило 2): копия любой прошлой
// версии открывается новой. Список общий у двух тестов и подключается
// `include!`: тест ядра (`crates/core/tests/backups.rs`) открывает шапку
// каждого образца и следит, что ни один файл папки не забыт, а браузерный
// тест окна (`crates/app/src/store/tests/backup.rs`) расшифровывает его
// WebCrypto и восстанавливает в базу — шифра в ядре нет.
//
// Файлы — история: их сохранила сама выпущенная версия через окно, и новый
// код их не перегенерирует никогда, иначе тест проверял бы сам себя.
// Новый образец — файл в `vN/` и строка здесь; числа строки выписаны
// человеком из файла и из того, как он сделан, а не посчитаны кодом.
//
// Последний образец восстанавливает и проверка собранного сайта
// (`tools/browser/check.mjs`), и она ждёт от него данных, а не только шапки.
// Выпущенные документы — для карточки и PDF. Закрытый III квартал 2026 года,
// чей полный пересчёт разошёлся со снимком (так в образце 0.0.69, проверено
// 2026-11-03), — для слов выгрузки и её листа закрытых кварталов
// (задача 83). Новый образец делается поверх прежнего, а III квартал 2026
// в нём не открывают и не закрывают заново: иначе CI покраснеет на словах
// выгрузки без видимой причины.
//
// ՀՎՀՀ в новом образце — только выдуманный (с 0.0.182, решение человека
// 2026-11-23, задача 121): репозиторий публичный, пароль образца — здесь же,
// а образцы до 0.0.171 несут прежний настоящий номер ИП (исключение —
// `.claude/rules/process/release.md`, Правило 11). С образца 0.0.182 вся
// цепочка — на выдуманном `07654321`, и новый образец поверх него чист сам.
// Ключи лицензий образцов подписаны парой проб тестов (закрытый ключ —
// 32 байта 7), а не ключом автора: ключ автора в публичном образце был бы
// рабочим ключом для любого, кто восстановит образец паролем отсюда.

